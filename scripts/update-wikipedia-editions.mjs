/**
 * Regenerates src/data/wikipediaEditions.json from Wikimedia sitematrix +
 * MediaWiki languageinfo. Run occasionally when new language Wikipedias
 * appear or language metadata changes:
 *
 *   node scripts/update-wikipedia-editions.mjs
 *
 * The catalog lists EVERY open content Wikipedia. The app's MVP picker can
 * still show a small featured set; visibility is a UI concern, not a data
 * concern — keep the seed complete.
 */
import { writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(ROOT, 'src/core/i18n/wikipediaEditions.catalog.json')
const JS_OUT = join(ROOT, 'src/core/i18n/wikipediaEditions.catalog.js')

const SITEMATRIX_URL =
  'https://meta.wikimedia.org/w/api.php?action=sitematrix&smsiteprop=url|dbname|code|lang|sitename&format=json'
const LANGUAGEINFO_URL =
  'https://www.mediawiki.org/w/api.php?action=query&meta=languageinfo&liprop=code|dir|autonym|name|fallbacks|bcp47&uselang=en&format=json'

/** Scripts where Latin sentence-end + capital-letter heuristics fail badly. */
const CJK = new Set([
  'zh',
  'zh-yue',
  'zh-classical',
  'zh-min-nan',
  'ja',
  'ko',
  'wuu',
  'gan',
  'hak',
  'cdo',
  'cjy',
])
const NO_SPACE = new Set(['th', 'lo', 'my', 'km', 'bo'])
const NO_CAPS = new Set([
  'ar',
  'arc',
  'ary',
  'arz',
  'azb',
  'ckb',
  'dv',
  'fa',
  'glk',
  'he',
  'ks',
  'mzn',
  'nqo',
  'pnb',
  'ps',
  'sd',
  'skr',
  'ug',
  'ur',
  'yi',
])

/**
 * Featured in the MVP language picker. The catalog still contains every
 * open Wikipedia; this only affects default picker prominence.
 */
const FEATURED = new Set(['en', 'de', 'fr', 'es', 'he', 'ar'])

function sentenceModel(code, dir) {
  if (CJK.has(code) || code.startsWith('zh')) return 'char-estimate'
  if (NO_SPACE.has(code)) return 'char-estimate'
  if (NO_CAPS.has(code) || dir === 'rtl') return 'unicode-punct'
  return 'latin-punct'
}

function lushnessSupport(model) {
  if (model === 'latin-punct') return 'full'
  if (model === 'unicode-punct') return 'relative'
  return 'experimental'
}

function isOpenWikipedia(site) {
  if (site.code !== 'wiki') return false
  // MediaWiki marks closed/private/fishbowl with the key present (often "").
  if ('closed' in site || 'private' in site || 'fishbowl' in site) return false
  return true
}

async function fetchJson(url) {
  const response = await fetch(url, {
    headers: { 'Api-User-Agent': 'WikiRealms/0.1 (edition-catalog-script; https://github.com/)' },
  })
  if (!response.ok) {
    throw new Error(`Failed to fetch ${url}: ${response.status}`)
  }
  return response.json()
}

async function main() {
  const [sitematrixPayload, languageinfoPayload] = await Promise.all([
    fetchJson(SITEMATRIX_URL),
    fetchJson(LANGUAGEINFO_URL),
  ])

  const sitematrix = sitematrixPayload.sitematrix
  const languageinfo = languageinfoPayload.query?.languageinfo ?? {}
  const editions = []

  for (const [key, entry] of Object.entries(sitematrix)) {
    if (key === 'count' || key === 'specials') continue
    if (!entry?.site || !entry.code) continue

    const wiki = entry.site.find(isOpenWikipedia)
    if (!wiki) continue

    const code = entry.code
    const info = languageinfo[code] ?? {}
    const dir = info.dir === 'rtl' ? 'rtl' : 'ltr'
    const model = sentenceModel(code, dir)

    editions.push({
      code,
      bcp47: info.bcp47 || code,
      name: info.name || entry.localname || entry.name || code,
      autonym: info.autonym || entry.name || code,
      dir,
      fallbacks: Array.isArray(info.fallbacks) ? info.fallbacks : [],
      sitename: wiki.sitename || 'Wikipedia',
      url: wiki.url,
      dbname: wiki.dbname,
      sentenceModel: model,
      lushnessSupport: lushnessSupport(model),
      featured: FEATURED.has(code),
    })
  }

  editions.sort((a, b) => a.code.localeCompare(b.code))

  const payload = {
    generatedAt: new Date().toISOString(),
    source: {
      sitematrix: SITEMATRIX_URL,
      languageinfo: LANGUAGEINFO_URL,
    },
    editions,
  }

  await writeFile(OUT, `${JSON.stringify(payload, null, 2)}\n`, 'utf8')

  await writeFile(
    JS_OUT,
    `/** Auto-generated by scripts/update-wikipedia-editions.mjs — do not edit. */\nexport default ${JSON.stringify(payload)}\n`,
    'utf8',
  )
  console.log(`Wrote ${editions.length} editions → ${OUT}`)
  console.log(`Wrote JS module → ${JS_OUT}`)
  console.log(
    `featured=${editions.filter((e) => e.featured).length} rtl=${editions.filter((e) => e.dir === 'rtl').length} experimental=${editions.filter((e) => e.lushnessSupport === 'experimental').length}`,
  )
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
